import QRCode from "qrcode";
import { requireRole } from "@/lib/auth/rbac";
import { requireModule } from "@/lib/tenant/modules";
import { getTenantSlug } from "@/lib/tenant/context";
import { getT } from "@/lib/terms/server";
import { getBaseUrl } from "@/lib/utils";
import { PrintButton } from "./print-button";

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export default async function WalkInQrPage({ searchParams }: { searchParams: Promise<{ l?: string }> }) {
  await requireRole("owner", "admin", "provider", "assistant");
  await requireModule("walk_in_queue");
  const { l } = await searchParams;
  const slug = await getTenantSlug();
  const t = await getT("queue", slug);

  const url = `${getBaseUrl()}/q/${slug}${l && UUID_RE.test(l) ? `?l=${l}` : ""}`;
  const svg = await QRCode.toString(url, { type: "svg", margin: 1, width: 512 });

  return (
    <div className="mx-auto flex max-w-xl flex-col items-center gap-6 p-6 text-center">
      <h1 className="text-3xl font-bold">{t("qr.title")}</h1>
      {/* The SVG is generated by the qrcode library from our own URL. */}
      <div className="w-full max-w-[512px]" dangerouslySetInnerHTML={{ __html: svg }} />
      <p className="break-all text-lg">{t("qr.subtitle", { url })}</p>
      <PrintButton label={t("qr.print")} />
    </div>
  );
}
